declare(strict_types=1);

require_once __DIR__ . '/CloakClient.php';

use IpCloak\IntegrationKit\CloakClient;

/**
 * Perform environment preflight checks.
 *
 * @return array<string, mixed>
 */
function cloak_check_environment(): array
{
    $phpOk = version_compare(PHP_VERSION, '7.4.0', '>=');
    $curlOk = extension_loaded('curl') && function_exists('curl_init');
    $jsonOk = extension_loaded('json') && function_exists('json_encode');
    $writableOk = is_writable(__DIR__);

    return [
        'php_version' => PHP_VERSION,
        'php_ok'      => $phpOk,
        'curl_ok'     => $curlOk,
        'json_ok'     => $jsonOk,
        'writable_ok' => $writableOk,
        'all_passed'  => ($phpOk && $curlOk && $jsonOk && $writableOk),
    ];
}

/**
 * Ping the configured Decision API endpoint with a diagnostic check.
 *
 * @return array<string, mixed>
 */
function cloak_ping_endpoint(string $endpoint, string $storeToken, int $timeoutMs = 800): array
{
    $client = new CloakClient([
        'store_token' => $storeToken,
        'endpoint'    => $endpoint,
        'timeout_ms'  => $timeoutMs,
    ]);

    $samplePayload = [
        'store_token' => $storeToken,
        'visitor'     => [
            'ip'              => '203.0.113.1',
            'ua'              => 'CloakInstallerPing/1.0',
            'accept_language' => 'en-US,en;q=0.9',
            'referer'         => '',
            'sec_ch_ua'       => '',
            'url'             => 'https://example.com/?installer_ping=1',
            'click_ids'       => [],
        ],
    ];

    return $client->verifyVisitor($samplePayload);
}

/**
 * Write cloak-config.json and generate the bootstrap entry file gate.php.
 *
 * @param array<string, mixed> $options
 * @return array<string, mixed>
 */
function cloak_install_files(array $options): array
{
    $targetDir = (string) ($options['target_dir'] ?? __DIR__);
    $config = [
        'store_token'    => (string) ($options['store_token'] ?? 'demo_store_token_local'),
        'endpoint'       => (string) ($options['endpoint'] ?? 'http://127.0.0.1:8787/v1/decision'),
        'default_mode'   => (string) ($options['default_mode'] ?? 'render_safe'),
        'timeout_ms'     => max(100, (int) ($options['timeout_ms'] ?? 800)),
        'safe_page_path' => $targetDir . '/safe-page.html',
        'installed_at'   => gmdate('c'),
    ];

    $configPath = rtrim($targetDir, '/') . '/cloak-config.json';
    $gatePath   = rtrim($targetDir, '/') . '/gate.php';

    $configJson = json_encode($config, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
    if ($configJson === false || file_put_contents($configPath, $configJson . "\n") === false) {
        return [
            'ok'    => false,
            'error' => 'Failed to write cloak-config.json',
        ];
    }

    $gateSource = <<<'PHP'
<?php
/**
 * Auto-generated by IpCloak PHP Installer (install.php)
 * Include this file at the top of your front controller (e.g., index.php):
 *   require_once __DIR__ . '/gate.php';
 */
declare(strict_types=1);

require_once __DIR__ . '/CloakClient.php';

$cloakConfigFile = __DIR__ . '/cloak-config.json';
$cloakConfig = is_file($cloakConfigFile)
    ? (json_decode((string) file_get_contents($cloakConfigFile), true) ?: [])
    : [];

$cloakGate = new \IpCloak\IntegrationKit\CloakClient($cloakConfig);
$cloakGate->enforce();
PHP;

    if (file_put_contents($gatePath, $gateSource . "\n") === false) {
        return [
            'ok'    => false,
            'error' => 'Failed to write gate.php',
        ];
    }

    return [
        'ok'          => true,
        'config_path' => $configPath,
        'gate_path'   => $gatePath,
        'config'      => $config,
    ];
}

// ============================================================================
// Mode 1: CLI Execution (`php install.php --token=xxx --endpoint=xxx --mode=redirect`)
// ============================================================================
if (PHP_SAPI === 'cli') {
    $longOpts = [
        'token::',
        'endpoint::',
        'mode::',
        'timeout::',
        'target-dir::',
        'ping',
        'help',
    ];
    $cliOpts = getopt('', $longOpts) ?: [];

    if (isset($cliOpts['help'])) {
        echo "IpCloak PHP Installer (CLI Mode)\n";
        echo "Usage:\n";
        echo "  php install.php --token=YOUR_TOKEN --endpoint=http://127.0.0.1:8787/v1/decision --mode=render_safe\n\n";
        echo "Options:\n";
        echo "  --token=<string>       Store identification token\n";
        echo "  --endpoint=<url>       Decision API HTTP POST endpoint\n";
        echo "  --mode=<string>        Default fallback mode: render_safe | redirect | not_found\n";
        echo "  --timeout=<ms>         Request timeout in milliseconds (default: 800)\n";
        echo "  --target-dir=<path>    Directory to write cloak-config.json & gate.php\n";
        echo "  --ping                 Run connectivity self-test against endpoint\n";
        exit(0);
    }

    $env = cloak_check_environment();
    echo "[1/3] Checking PHP Environment...\n";
    echo "  - PHP Version (>=7.4) : " . $env['php_version'] . ($env['php_ok'] ? " [OK]" : " [FAIL]") . "\n";
    echo "  - ext-curl loaded     : " . ($env['curl_ok'] ? "Yes [OK]" : "No [FAIL]") . "\n";
    echo "  - ext-json loaded     : " . ($env['json_ok'] ? "Yes [OK]" : "No [FAIL]") . "\n";

    if (!$env['php_ok'] || !$env['curl_ok'] || !$env['json_ok']) {
        fwrite(STDERR, "Environment check failed. Please enable PHP >= 7.4, ext-curl, and ext-json.\n");
        exit(1);
    }

    $token     = (string) ($cliOpts['token'] ?? 'demo_store_token_local');
    $endpoint  = (string) ($cliOpts['endpoint'] ?? 'http://127.0.0.1:8787/v1/decision');
    $mode      = (string) ($cliOpts['mode'] ?? 'render_safe');
    $timeout   = (int) ($cliOpts['timeout'] ?? 800);
    $targetDir = (string) ($cliOpts['target-dir'] ?? __DIR__);

    echo "[2/3] Writing cloak-config.json and generating gate.php...\n";
    $installResult = cloak_install_files([
        'store_token'  => $token,
        'endpoint'     => $endpoint,
        'default_mode' => $mode,
        'timeout_ms'   => $timeout,
        'target_dir'   => $targetDir,
    ]);

    if (!$installResult['ok']) {
        fwrite(STDERR, "Install Error: " . $installResult['error'] . "\n");
        exit(1);
    }

    echo "  - Config saved : " . $installResult['config_path'] . "\n";
    echo "  - Gate saved   : " . $installResult['gate_path'] . "\n";

    echo "[3/3] Connectivity Self-Test...\n";
    if (isset($cliOpts['ping'])) {
        $ping = cloak_ping_endpoint($endpoint, $token, $timeout);
        echo "  - Ping Result  : " . json_encode($ping, JSON_UNESCAPED_SLASHES) . "\n";
    } else {
        echo "  - Skipped live ping (pass --ping to verify live endpoint connectivity).\n";
    }

    echo "\nInstallation complete! Add this line to the top of your index.php:\n";
    echo "  require_once __DIR__ . '/gate.php';\n";
    exit(0);
}

// ============================================================================
// Mode 2: Web Form Setup Wizard
// ============================================================================
$env = cloak_check_environment();
$message = '';
$pingReport = null;

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
    $submittedToken    = trim((string) ($_POST['store_token'] ?? 'demo_store_token_local'));
    $submittedEndpoint = trim((string) ($_POST['endpoint'] ?? 'http://127.0.0.1:8787/v1/decision'));
    $submittedMode     = trim((string) ($_POST['default_mode'] ?? 'render_safe'));
    $submittedTimeout  = max(100, (int) ($_POST['timeout_ms'] ?? 800));
    $actionType        = (string) ($_POST['wizard_action'] ?? 'install');

    if ($actionType === 'ping') {
        $pingReport = cloak_ping_endpoint($submittedEndpoint, $submittedToken, $submittedTimeout);
    } else {
        $res = cloak_install_files([
            'store_token'  => $submittedToken,
            'endpoint'     => $submittedEndpoint,
            'default_mode' => $submittedMode,
            'timeout_ms'   => $submittedTimeout,
        ]);
        $message = $res['ok']
            ? 'Configuration saved to cloak-config.json and gate.php generated successfully.'
            : ('Error: ' . $res['error']);
    }
}
